            InitializeComponent();
            DiscordNavigationItem.Image = CreateDiscordIcon();

            App.Logger.WriteLine("MainWindow", "Initializing settings window");

            if (showAlreadyRunningWarning)
                ShowAlreadyRunningSnackbar();

            LoadState();

            ShowWhatsNewIfNeeded();
        }

